def _decode_attr(value: Any) -> Any:
    """Make HDF5 attributes friendlier for metadata dictionaries."""
    if isinstance(value, bytes):
        return value.decode("utf-8", errors="replace")
    if isinstance(value, np.generic):
        return value.item()
    return value


def _read_optional_dataset(f: h5py.File, name: str) -> Optional[np.ndarray]:
    return f[name][:] if name in f else None


def load_sashimi_boost_table(
    filename: Optional[str | os.PathLike[str]] = None,
    *,
    boost_key: str = "boost_total",
    z_key: str = "z",
    mass_key: str = "m_host",
    read_diagnostic_masks: bool = True,
) -> Dict[str, Any]:
    """Load a SASHIMI-C subhalo boost table from HDF5.

    Parameters
    ----------
    filename:
        Path to the HDF5 table. If omitted, use :func:`default_sashimi_boost_path`.
    boost_key:
        Dataset containing the production multiplier. Default: ``boost_total``.
    z_key:
        Redshift grid dataset. Default: ``z``.
    mass_key:
        Host mass grid dataset in solar masses. Default: ``m_host``.
    read_diagnostic_masks:
        If True, also read available masks such as ``valid_clean``,
        ``interp_mask`` and ``fallback_mask`` into the output dictionary.

    Returns
    -------
    dict
        A dictionary with at least ``z``, ``m_host``, ``boost_total``,
        ``attrs`` and ``filename``.
    """
    path = Path(filename) if filename is not None else default_sashimi_boost_path()
    if not path.exists():
        raise FileNotFoundError(
            f"SASHIMI boost table not found: {path}\n"
            "Either generate it with build_sashimi_boost_table_continuous_margin.ipynb "
            "or pass the correct filename explicitly."
        )

    with h5py.File(path, "r") as f:
        missing = [key for key in (z_key, mass_key, boost_key) if key not in f]
        if missing:
            raise KeyError(
                f"Missing dataset(s) {missing} in {path}. "
                f"Available datasets: {list(f.keys())}"
            )

        z = np.asarray(f[z_key][:], dtype=float)
        m_host = np.asarray(f[mass_key][:], dtype=float)
        boost = np.asarray(f[boost_key][:], dtype=float)

        data: Dict[str, Any] = {
            "filename": str(path),
            "z": z,
            "m_host": m_host,
            "boost_total": boost,
            "attrs": {k: _decode_attr(v) for k, v in f.attrs.items()},
        }

        if read_diagnostic_masks:
            for name in (
                "boost_raw",
                "Bsh_raw",
                "fsh_raw",
                "n_sub_eff_raw",
                "valid_raw",
                "valid_clean",
                "outlier_mask",
                "inside_domain_mask",
                "inside_domain_padded_mask",
                "boundary_pad_mask",
                "interp_mask",
                "fallback_mask",
                "below_clip_mask",
                "failure_code",
                "min_valid_mass",
                "max_valid_mass",
                "zmax",
                "zmax_margin",
            ):
                arr = _read_optional_dataset(f, name)
                if arr is not None:
                    data[name] = arr

    _validate_sashimi_boost_arrays(z, m_host, boost, path)
    return data


def _validate_sashimi_boost_arrays(
    z: np.ndarray,
    m_host: np.ndarray,
    boost: np.ndarray,
    filename: str | os.PathLike[str],
) -> None:
    """Validate the minimal table structure before building an interpolator."""
    if z.ndim != 1:
        raise ValueError(f"{filename}: z must be one-dimensional, got shape {z.shape}.")
    if m_host.ndim != 1:
        raise ValueError(
            f"{filename}: m_host must be one-dimensional, got shape {m_host.shape}."
        )
    if boost.shape != (len(z), len(m_host)):
        raise ValueError(
            f"{filename}: boost table shape must be (len(z), len(m_host)) = "
            f"{(len(z), len(m_host))}, got {boost.shape}."
        )
    if len(z) < 2 or len(m_host) < 2:
        raise ValueError(f"{filename}: z and m_host grids must have at least 2 points.")
    if not np.all(np.diff(z) > 0):
        raise ValueError(f"{filename}: z grid must be strictly increasing.")
    if not np.all(np.diff(m_host) > 0):
        raise ValueError(f"{filename}: m_host grid must be strictly increasing.")
    if not np.all(m_host > 0):
        raise ValueError(f"{filename}: all host masses must be positive.")
    if not np.all(np.isfinite(boost)):
        raise ValueError(f"{filename}: boost table contains non-finite values.")


def build_sashimi_boost_interpolator(
    filename: Optional[str | os.PathLike[str]] = None,
    *,
    boost_key: str = "boost_total",
    fallback_to_unity: bool = True,
    clip_min_boost: float = 1.0,
    read_diagnostic_masks: bool = True,
) -> Tuple[Callable[[Any, Any], np.ndarray | float], Dict[str, Any]]:
    """Build a callable boost interpolator from the SASHIMI-C HDF5 table.

    The callable has signature

        boost(Mhost, z)

    and supports scalar or array inputs with NumPy broadcasting.

    Parameters
    ----------
    filename:
        Path to the SASHIMI HDF5 table. If omitted, use the default path.
    boost_key:
        Dataset to interpolate. Production use should keep ``boost_total``.
    fallback_to_unity:
        If True, outside-table points return 1. If False, scipy extrapolates
        linearly outside the table because ``fill_value=None``.
    clip_min_boost:
        Minimum returned boost. Use 1.0 for the conservative production
        convention. Set to ``None`` to disable clipping.
    read_diagnostic_masks:
        Include optional diagnostic arrays in the returned metadata.

    Returns
    -------
    interpolator, metadata
        ``interpolator(Mhost, z)`` returns the boost multiplier.
        ``metadata`` contains the loaded table and useful attributes.
    """
    table = load_sashimi_boost_table(
        filename,
        boost_key=boost_key,
        read_diagnostic_masks=read_diagnostic_masks,
    )
    z_grid = table["z"]
    m_grid = table["m_host"]
    boost_table = table["boost_total"]

    fill_value = 1.0 if fallback_to_unity else None
    rgi = RegularGridInterpolator(
        (z_grid, np.log(m_grid)),
        boost_table,
        bounds_error=False,
        fill_value=fill_value,
    )

    log_m_min = float(np.log(m_grid[0]))
    log_m_max = float(np.log(m_grid[-1]))
    z_min = float(z_grid[0])
    z_max = float(z_grid[-1])

    def interpolator(Mhost: Any, z: Any) -> np.ndarray | float:
        M_arr = np.asarray(Mhost, dtype=float)
        z_arr = np.asarray(z, dtype=float)
        z_b, M_b = np.broadcast_arrays(z_arr, M_arr)

        out = np.ones(z_b.shape, dtype=float)

        good_mass = np.isfinite(M_b) & (M_b > 0)
        good_z = np.isfinite(z_b)
        good = good_mass & good_z

        if np.any(good):
            pts = np.column_stack(
                [
                    z_b[good].ravel(),
                    np.log(M_b[good]).ravel(),
                ]
            )
            vals = np.asarray(rgi(pts), dtype=float)

            # If fallback_to_unity=False, extrapolation may still produce
            # non-finite or sub-unity values; handle these conservatively.
            vals = np.where(np.isfinite(vals), vals, 1.0)
            if clip_min_boost is not None:
                vals = np.maximum(vals, float(clip_min_boost))

            out[good] = vals.reshape(-1)

        if out.shape == ():
            return float(out)
        return out

    metadata: Dict[str, Any] = dict(table)
    metadata.update(
        {
            "table": boost_table,  # backward-compatible alias
            "M_grid": m_grid,
            "z_grid": z_grid,
            "boost_key": boost_key,
            "fallback_to_unity": bool(fallback_to_unity),
            "clip_min_boost": clip_min_boost,
            "interpolation_space": "(z, log(m_host))",
            "interpolation_quantity": "B, not logB",
            "z_min": z_min,
            "z_max": z_max,
            "m_host_min": float(m_grid[0]),
            "m_host_max": float(m_grid[-1]),
            "log_m_host_min": log_m_min,
            "log_m_host_max": log_m_max,
        }
    )
    return interpolator, metadata


def load_sashimi_boost_interpolator(
    filename: Optional[str | os.PathLike[str]] = None,
    **kwargs: Any,
) -> Callable[[Any, Any], np.ndarray | float]:
    """Convenience wrapper returning only the SASHIMI boost interpolator."""
    interpolator, _metadata = build_sashimi_boost_interpolator(filename, **kwargs)
    return interpolator


def sashimi_total_boost(
    Mhost: Any,
    z: Any,
    filename: Optional[str | os.PathLike[str]] = None,
    **kwargs: Any,
) -> np.ndarray | float:
    """Evaluate the SASHIMI table boost directly.

    This is convenient for one-off checks. For loops, build the interpolator once
    with :func:`build_sashimi_boost_interpolator` and reuse it.
    """
    interp = load_sashimi_boost_interpolator(filename, **kwargs)
    return interp(Mhost, z)


def describe_sashimi_table(metadata: Mapping[str, Any]) -> str:
    """Return a compact human-readable summary of a loaded SASHIMI table."""
    filename = metadata.get("filename", "<unknown>")
    z_min = metadata.get("z_min", np.nan)
    z_max = metadata.get("z_max", np.nan)
    m_min = metadata.get("m_host_min", np.nan)
    m_max = metadata.get("m_host_max", np.nan)
    table = metadata.get("boost_total", metadata.get("table", None))
    if table is None:
        b_min = b_max = np.nan
    else:
        b_min = float(np.nanmin(table))
        b_max = float(np.nanmax(table))
    return (
        f"SASHIMI-C HDF5 boost table: {filename}; "
        f"z=[{z_min:.6g}, {z_max:.6g}], "
        f"Mhost=[{m_min:.6e}, {m_max:.6e}] Msun, "
        f"Btot=[{b_min:.6g}, {b_max:.6g}], "
        f"fallback_to_unity={metadata.get('fallback_to_unity', None)}, "
        f"clip_min_boost={metadata.get('clip_min_boost', None)}"
    )


