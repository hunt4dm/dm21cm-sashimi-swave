# ----- Subhalo mass function: m^2 dN/dm = (a + b m^alpha) exp[-(m/mc)^beta]

def a_sub(Mhost: float, z: float) -> float:
    logM = np.log10(Mhost)
    return (
        6.0e-4
        * Mhost
        * (2 - 0.08 * logM) ** 2
        * (np.log10(Mhost / 1e-5)) ** (-0.1)
        * (1 + z)
    )


def b_sub(Mhost: float, z: float) -> float:
    logM = np.log10(Mhost)
    return (
        8.0e-5
        * Mhost
        * (2 - 0.08 * logM)
        * (np.log10(Mhost / 1e-5)) ** (-0.08 * z)
        * (np.log10(Mhost / 1e-8)) ** (-1)
        * (np.log10(Mhost / 1e18)) ** 2
    )


def mc_sub(Mhost: float, z: float) -> float:
    return 0.05 * (1 + z) * Mhost


def alpha_sub(z: float) -> float:
    return 0.2 + 0.02 * z


def beta_sub() -> float:
    return 3.0


def m2_dNdm_sub(m: float, Mhost: float, z: float) -> float:
    aa = a_sub(Mhost, z)
    bb = b_sub(Mhost, z)
    al = alpha_sub(z)
    be = beta_sub()
    mc = mc_sub(Mhost, z)
    return (aa + bb * m ** al) * np.exp(-(m / mc) ** be)


def dNdm_sub(m: float, Mhost: float, z: float) -> float:
    return m2_dNdm_sub(m, Mhost, z) / (m ** 2)


def get_fsh_mmax(Mhost: float, z: float, mode: str = "mc") -> float:
    """Upper integration limit for the legacy f_sh calculation."""
    if mode == "mc":
        return mc_sub(Mhost, z)
    if mode == "0.1M":
        return 0.1 * Mhost
    if mode == "M":
        return Mhost
    raise ValueError("mode must be 'mc', '0.1M', or 'M'.")


def f_sh(
    Mhost: float,
    z: float,
    m_min: float = 1e-6,
    m_max: Optional[float] = None,
    epsrel: float = 1e-6,
    mmax_mode: str = "mc",
) -> float:
    """Legacy subhalo mass fraction."""
    if Mhost <= 0:
        raise ValueError("Mhost must be positive.")
    if m_max is None:
        m_max = get_fsh_mmax(Mhost, z, mode=mmax_mode)
    if m_min <= 0 or m_max <= m_min:
        raise ValueError("Need m_max > m_min > 0.")

    def integrand_ln_m(lnm: float) -> float:
        m = np.exp(lnm)
        return (m * dNdm_sub(m, Mhost, z)) * m

    val, _err = quad(
        integrand_ln_m,
        np.log(m_min),
        np.log(m_max),
        epsrel=epsrel,
        limit=500,
    )
    return float(val / Mhost)


# ----- Legacy B_sh fitting functions

def X_correa(z: float) -> float: return 2.7 * np.exp(-0.2 * z) + 0.15
def Y_correa(z: float) -> float: return 0.4 + (-0.224 * z + 0.56) * np.exp(-0.8 * z)
def a_correa(z: float) -> float: return 0.10 + 0.095 * np.exp(-0.5 * z)
def b_correa(z: float) -> float: return 0.03 * z ** 2 - 0.08 * z - 0.83
def c_correa(z: float) -> float: return 0.004 * z ** 2 - 0.04 * z - 0.6
def m1_correa(z: float) -> float: return -3.17 * z + 17.4
def m2_correa(z: float) -> float: return -(0.2 * z - 1.0) ** 5 - 4.0

def X_okoli(z: float) -> float: return 2.2 * np.exp(-0.75 * z) + 0.67
def Y_okoli(z: float) -> float: return 2.5 * np.exp(-0.005 * z) + 0.8
def a_okoli(z: float) -> float: return 0.1 * np.exp(-0.5 * z) + 0.22
def b_okoli(z: float) -> float: return 0.8 * np.exp(-0.5 * (z - 12.0) ** 4) - 0.24
def c_okoli(z: float) -> float: return -0.0005 * z ** 3 - 0.032 * z ** 2 + 0.28 * z - 1.12
def m1_okoli(z: float) -> float: return -2.6 * z + 8.2
def m2_okoli(z: float) -> float: return 0.1 * np.exp(-3.0 * z) - 12.0


def log10_Bsh(Mhost: float, z: float, model: str = "correa") -> float:
    """Legacy log10 of the subhalo annihilation boost B_sh."""
    if Mhost <= 0:
        raise ValueError("Mhost must be positive.")
    logM = np.log10(Mhost)

    if model.lower() == "correa":
        X, Y = X_correa(z), Y_correa(z)
        aa, bb, cc = a_correa(z), b_correa(z), c_correa(z)
        m1, m2 = m1_correa(z), m2_correa(z)
    elif model.lower() == "okoli":
        X, Y = X_okoli(z), Y_okoli(z)
        aa, bb, cc = a_okoli(z), b_okoli(z), c_okoli(z)
        m1, m2 = m1_okoli(z), m2_okoli(z)
    else:
        raise ValueError("model must be 'correa' or 'okoli'.")

    term1 = X / (1.0 + np.exp(-aa * (logM - m1)))
    term2 = cc * (1.0 + Y / (1.0 + np.exp(-bb * (logM - m2))))
    return float(term1 + term2)


def B_sh(Mhost: float, z: float, model: str = "correa") -> float:
    return float(10 ** log10_Bsh(Mhost, z, model=model))


def boost_is_applicable(
    Mhost: float,
    z: float,
    host_m_min: Optional[float] = None,
    host_m_max: Optional[float] = None,
    z_max: Optional[float] = 6.0,
) -> bool:
    """Applicability gate for the legacy analytic prescription."""
    if z_max is not None and z > z_max:
        return False
    if host_m_min is not None and Mhost < host_m_min:
        return False
    if host_m_max is not None and Mhost > host_m_max:
        return False
    return True


def total_boost(
    Mhost: float,
    z: float,
    model: str = "correa",
    m_min: float = 1e-6,
    fsh_mmax_mode: str = "mc",
    host_m_min: Optional[float] = None,
    host_m_max: Optional[float] = None,
    z_max: Optional[float] = 6.0,
    fallback_to_unity: bool = True,
    integration_epsrel: float = 1e-6,
) -> float:
    """Legacy total luminosity multiplier L_total / L_host,0."""
    if not boost_is_applicable(
        Mhost,
        z,
        host_m_min=host_m_min,
        host_m_max=host_m_max,
        z_max=z_max,
    ):
        if fallback_to_unity:
            return 1.0
        raise ValueError("Requested subhalo boost outside applicability range.")

    fsh = f_sh(
        Mhost,
        z,
        m_min=m_min,
        m_max=None,
        epsrel=integration_epsrel,
        mmax_mode=fsh_mmax_mode,
    )
    bsh = B_sh(Mhost, z, model=model)
    return float(max(1.0, 1.0 - fsh ** 2 + bsh))


def build_analytic_total_boost_interpolator(
    model: str = "correa",
    m_min: float = 1e-6,
    fsh_mmax_mode: str = "mc",
    host_m_min: float = 1e-4,
    host_m_max: float = 1e14,
    z_max: float = 6.0,
    fallback_to_unity: bool = True,
    integration_epsrel: float = 1e-6,
    z_grid: Optional[np.ndarray] = None,
    M_grid: Optional[np.ndarray] = None,
    **_unused: Any,
) -> Tuple[Callable[[Any, Any], np.ndarray | float], Dict[str, Any]]:
    """Build the old analytic boost interpolator.

    This function is retained only for comparison/reproducibility.
    Production s-wave tables should use the SASHIMI HDF5 table.
    """
    if z_grid is None:
        z_grid = np.linspace(0.0, z_max, 61)
    else:
        z_grid = np.asarray(z_grid, dtype=float)

    if M_grid is None:
        M_grid = np.geomspace(host_m_min, host_m_max, 161)
    else:
        M_grid = np.asarray(M_grid, dtype=float)

    table = np.zeros((len(z_grid), len(M_grid)), dtype=float)
    for i_z, zz in enumerate(z_grid):
        for i_m, mm in enumerate(M_grid):
            table[i_z, i_m] = total_boost(
                mm,
                zz,
                model=model,
                m_min=m_min,
                fsh_mmax_mode=fsh_mmax_mode,
                host_m_min=host_m_min,
                host_m_max=host_m_max,
                z_max=z_max,
                fallback_to_unity=fallback_to_unity,
                integration_epsrel=integration_epsrel,
            )

    rgi = RegularGridInterpolator(
        (z_grid, np.log(M_grid)),
        table,
        bounds_error=False,
        fill_value=1.0 if fallback_to_unity else None,
    )

    def interpolator(Mhost: Any, z: Any) -> np.ndarray | float:
        M_arr = np.asarray(Mhost, dtype=float)
        z_arr = np.asarray(z, dtype=float)
        z_b, M_b = np.broadcast_arrays(z_arr, M_arr)

        out = np.ones(z_b.shape, dtype=float)
        good = np.isfinite(z_b) & np.isfinite(M_b) & (M_b > 0)
        if np.any(good):
            pts = np.column_stack([z_b[good].ravel(), np.log(M_b[good]).ravel()])
            vals = np.asarray(rgi(pts), dtype=float)
            vals = np.where(np.isfinite(vals), vals, 1.0)
            vals = np.maximum(vals, 1.0)
            out[good] = vals.reshape(-1)

        if out.shape == ():
            return float(out)
        return out

    metadata = {
        "model": model,
        "z_grid": z_grid,
        "M_grid": M_grid,
        "table": table,
        "boost_total": table,
        "fallback_to_unity": fallback_to_unity,
        "legacy_analytic": True,
    }
    return interpolator, metadata
