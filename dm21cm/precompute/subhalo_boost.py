def build_total_boost_interpolator(
    model: str = "sashimi",
    *,
    table_path: Optional[str | os.PathLike[str]] = None,
    filename: Optional[str | os.PathLike[str]] = None,
    fallback_to_unity: bool = True,
    clip_min_boost: float = 1.0,
    **legacy_kwargs: Any,
) -> Tuple[Callable[[Any, Any], np.ndarray | float], Dict[str, Any]]:
    """Build a total-boost interpolator.

    Recommended use:
        build_total_boost_interpolator(model="sashimi", table_path="...h5")

    For backward compatibility, ``model='correa'`` or ``model='okoli'`` still
    constructs the old analytic interpolator using the legacy keyword arguments.
    """
    model_lower = str(model).lower()

    if model_lower in ("sashimi", "sashimi_h5", "h5", "table"):
        path = table_path if table_path is not None else filename
        return build_sashimi_boost_interpolator(
            path,
            fallback_to_unity=fallback_to_unity,
            clip_min_boost=clip_min_boost,
        )

    if model_lower in ("correa", "okoli"):
        return build_analytic_total_boost_interpolator(
            model=model_lower,
            fallback_to_unity=fallback_to_unity,
            **legacy_kwargs,
        )

    raise ValueError(
        "Unknown subhalo boost model. Use 'sashimi' for the HDF5 table, "
        "or 'correa'/'okoli' for the legacy analytic prescription."
    )


def describe_model_configuration(
    model: str = "sashimi",
    *,
    table_path: Optional[str | os.PathLike[str]] = None,
    filename: Optional[str | os.PathLike[str]] = None,
    **kwargs: Any,
) -> str:
    """Human-readable model summary string."""
    model_lower = str(model).lower()
    if model_lower in ("sashimi", "sashimi_h5", "h5", "table"):
        path = table_path if table_path is not None else filename
        if path is None:
            path = default_sashimi_boost_path()
        return (
            f"model=sashimi_h5, table_path={path}, "
            f"fallback_to_unity={kwargs.get('fallback_to_unity', True)}, "
            f"clip_min_boost={kwargs.get('clip_min_boost', 1.0)}"
        )

    return (
        f"model={model}, m_min={kwargs.get('m_min', 1e-6):.6e}, "
        f"fsh_mmax_mode={kwargs.get('fsh_mmax_mode', 'mc')}, "
        f"host_m_min={kwargs.get('host_m_min', None)}, "
        f"host_m_max={kwargs.get('host_m_max', None)}, "
        f"z_max={kwargs.get('z_max', 6.0)}"
    )


