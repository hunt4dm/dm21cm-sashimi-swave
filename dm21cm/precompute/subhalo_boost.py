"""Subhalo boost helper functions for s-wave annihilation precompute tables.

This module is centered on the new SASHIMI-C HDF5 boost table generated by

    build_sashimi_boost_table_continuous_margin.ipynb

The production table stores the total luminosity multiplier

    boost_total = L_total / L_host,0 = 1 - f_sh**2 + B_sh

on a regular grid in (z, m_host).  The table is intended to be used
multiplicatively on the host-only s-wave annihilation rate.

Conservative convention:
    - Interpolate directly in B, not log(B), matching the notebook.
    - Interpolate in (z, log(m_host)).
    - Outside the table, or for non-positive/invalid host masses, return 1.
    - Final returned values are clipped to be >= 1 by default.

The old analytic/Hiroshima-style functions are kept at the bottom for
backward compatibility, but the recommended production path is the SASHIMI
HDF5 table loader.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Callable, Dict, Mapping, Optional, Tuple

import h5py
import numpy as np
from scipy.integrate import quad
from scipy.interpolate import RegularGridInterpolator


